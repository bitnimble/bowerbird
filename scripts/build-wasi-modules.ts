// Builds the browser's threaded modules into `native/rawshim/pkg`, beside the module they are
// shipped with, under content-addressed names for the reason `hash-pkg.ts` gives: the AV1 decoder
// (`native/avif_planes`) and the editor's VP9 encoder on Firefox (`native/vp9_encode`).
//
// `wasm32-wasip1-threads` rather than `wasm32-unknown-unknown`: rav1d reaches for `libc` types the
// latter has no definition of, libvpx is C, and threads are what make a 24MP still take tens of
// milliseconds rather than seconds. The page supplies the threads itself (`web/src/wasi/`).

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const ROOT = join(import.meta.dir, '..');
const TARGET = 'wasm32-wasip1-threads';
const pkg = join(ROOT, 'native', 'rawshim', 'pkg');
const forwards = '// Generated by scripts/build-wasi-modules.ts.';

const MODULES = [
  { crate: 'avif_planes', urlExport: 'avifPlanesUrl' },
  { crate: 'vp9_encode', urlExport: 'vp9EncodeUrl' },
];

const RUSTFLAGS = [
  '-C target-feature=+simd128',
  '-C link-arg=--max-memory=1073741824',
  // A thread's entry, and the two initialisers a reactor module would run from `_initialize`:
  // this one links none, so without them the first `thread::spawn` waits on a thread record
  // nothing ever wrote.
  '-C link-arg=--export=wasi_thread_start',
  '-C link-arg=--export=__wasi_init_tp',
  '-C link-arg=--export=__wasm_call_ctors',
].join(' ');

function run(command: string, args: string[], env: NodeJS.ProcessEnv = process.env): void {
  const ran = spawnSync(command, args, { cwd: ROOT, stdio: 'inherit', env });
  if (ran.status !== 0)
    throw new Error(`${command} ${args.join(' ')} exited ${ran.status ?? 'on a signal'}`);
}

const installed = spawnSync('rustup', ['target', 'list', '--installed'], { encoding: 'utf8' });
if (installed.status !== 0)
  throw new Error('rustup is needed to add the wasm32-wasip1-threads target');
if (!installed.stdout.split('\n').includes(TARGET)) run('rustup', ['target', 'add', TARGET]);

await mkdir(pkg, { recursive: true });
for (const { crate, urlExport } of MODULES) {
  run(
    'bun',
    [
      'run',
      'scripts/cargo.ts',
      'build',
      '--release',
      '--target',
      TARGET,
      '--manifest-path',
      join(ROOT, 'native', crate, 'Cargo.toml'),
    ],
    { ...process.env, RUSTFLAGS },
  );

  const wasm = await readFile(
    join(ROOT, 'native', crate, 'target', TARGET, 'release', `${crate}.wasm`),
  );
  const hashed = `${crate}.${createHash('sha256').update(wasm).digest('hex').slice(0, 12)}.wasm`;
  await writeFile(join(pkg, hashed), wasm);
  await writeFile(
    join(pkg, `${crate}.js`),
    `${forwards}\nexport const ${urlExport} = new URL('./${hashed}', import.meta.url).href;\n`,
  );
  await writeFile(join(pkg, `${crate}.d.ts`), `${forwards}\nexport const ${urlExport}: string;\n`);
  const stale = new RegExp(`^${crate}\\.[0-9a-f]{12}\\.wasm$`);
  for (const entry of await readdir(pkg)) {
    if (stale.test(entry) && entry !== hashed) await rm(join(pkg, entry));
  }
  console.log(`pkg: ${hashed}`);
}
