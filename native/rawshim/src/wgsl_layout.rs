//! rawshim's uniform blocks, against the structs their shaders declare (`shaders::layout`).

#[cfg(test)]
mod tests {
    /// Every uniform block, against the struct the shader declares.
    ///
    /// The builders are called with whatever arguments produce a block - none of them branch on a
    /// value, they all write a fixed run of words - so the length is the whole of what is asked.
    #[test]
    fn every_uniform_is_the_size_its_shader_reads() {
        assert_eq!(
            crate::print::Scene::default()
                .uniform(units::light::Light::ZERO)
                .len(),
            112
        );
        // The blocks whose bytes a function returns. `base.rs` builds its other four inline into
        // the buffer they go to, so there is nothing to call and no length to take; extract them
        // the same way when one is next touched and add a line here.
        let cases = [
            (
                "print_light_calibrate.wgsl",
                "Lamp",
                shaders::PRINT_LIGHT_CALIBRATE.source,
                crate::print::light_uniform(
                    crate::print::Scene::default().light_parameters(),
                    6500.0,
                )
                .len(),
            ),
            (
                "frame.wgsl",
                "PrintParams",
                shaders::FRAME.source,
                crate::print::Scene::default()
                    .uniform(units::light::Light::ZERO)
                    .len(),
            ),
            (
                "assembly_levels.wgsl",
                "Params",
                shaders::ASSEMBLY_LEVELS.source,
                crate::assembly_levels::params_block(),
            ),
            (
                "assembly_blend.wgsl",
                "Params",
                shaders::ASSEMBLY_BLEND.source,
                crate::assembly_blend::params_block(),
            ),
            (
                "assembly_weight.wgsl",
                "Params",
                shaders::ASSEMBLY_WEIGHT.source,
                crate::assembly_weight::params_block(),
            ),
            (
                "composite_gather.wgsl",
                "Params",
                shaders::COMPOSITE_GATHER.source,
                crate::composite_tile::params_block(),
            ),
            (
                "composite_blend.wgsl",
                "Params",
                shaders::COMPOSITE_BLEND.source,
                crate::composite_tile::blend_block(),
            ),
            (
                "align_luma.wgsl",
                "Params",
                shaders::ALIGN_LUMA.source,
                crate::align::luma_block(),
            ),
            (
                "align.wgsl",
                "Params",
                shaders::ALIGN.source,
                crate::align::align_block(),
            ),
            (
                "merge.wgsl",
                "Params",
                shaders::MERGE.source,
                crate::merge::block(),
            ),
            (
                "fit_wide.wgsl",
                "Params",
                shaders::FIT_WIDE.source,
                crate::fit_wide::params_block(),
            ),
            (
                "repair.wgsl",
                "Params",
                shaders::REPAIR.source,
                crate::repair::params_block(),
            ),
            (
                "copy_rect.wgsl",
                "Params",
                shaders::COPY_RECT.source,
                crate::retouched_frame::params_block(),
            ),
            (
                "reduce.wgsl",
                "Reduction",
                shaders::REDUCE.source,
                crate::base::REDUCTION_BYTES,
            ),
            (
                "fit_pairs.wgsl",
                "Params",
                shaders::FIT_PAIRS.source,
                crate::fit_pairs::params_block(),
            ),
            (
                "fit_lattice.wgsl",
                "Params",
                shaders::FIT_LATTICE.source,
                crate::fit_lattice::params_block(),
            ),
            (
                "linearise.wgsl",
                "Params",
                shaders::LINEARISE.source,
                crate::linearise::BLOCK_BYTES,
            ),
        ];
        shaders::layout::check(&cases);
    }
}
